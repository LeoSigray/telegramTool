"""
Прогрев аккаунтов (по «Плану автоматизации прогрева»).

Устройство пакета — слои, чтобы каждый можно было проверять отдельно:

  config   — все числа и окна в одном месте (дни, паузы, окна суток)
  store    — SQLite: аккаунты в прогреве, очередь задач, пары, переписка, лог
  devices  — «человеческий» отпечаток устройства на аккаунт (стабильный)
  planner  — ЧИСТАЯ логика расписания (без сети и БД): что и когда делать
  content  — тексты через нейросеть (имя, био, юзернейм, реплики диалога)
  runner   — исполнитель: берёт созданные задачи и делает их через Telethon

Прогрев длится несколько суток, поэтому всё состояние лежит в БД, а не в
памяти: тул можно закрыть и открыть снова — прогрев продолжится с того места.
"""
