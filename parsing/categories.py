def detect_category(text: str, file_hint: str | None = None) -> str:
    """
    Определяет категорию по тексту (название чата) и опционально по подсказке файла.
    Возвращает название категории или 'Другое'.
    """
    text = (text or "").lower()
    if file_hint:
        fh = file_hint.lower()
        for cat, keywords in ALL_CATEGORIES.items():
            if any(kw in fh for kw in keywords):
                return cat
    for cat, keywords in ALL_CATEGORIES.items():
        if any(kw in text for kw in keywords):
            return cat
    return "Другое"


def map_zip_category(zip_category_name: str) -> str:
    """
    Маппит название категории из ZIP-файла в нашу систему категорий.
    Если маппинг не найден, возвращает как есть.
    """
    return ZIP_CATEGORY_MAP.get(zip_category_name, zip_category_name)


def detect_city(text: str) -> str | None:
    """Определяет город по тексту. Возвращает название города или None."""
    text = (text or "").lower()
    for city in CITIES:
        if city.lower() in text:
            return city
    return None


def sanitize_sheet_name(name: str) -> str:
    """Очищает название для использования как имя листа Excel (макс 31 символ)."""
    name = (name or "Другое").strip()
    name = re.sub(r"[\[\]\*:/\\\?\n]", " ", name)
    return name[:31]
