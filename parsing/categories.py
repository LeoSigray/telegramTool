def _check_keywords(text: str, keywords: list) -> bool:
    """Умный поиск ключевых слов с учётом коротких слов."""
    text = (text or "").lower()
    for kw in keywords:
        kw = kw.lower()
        if len(kw) <= 3:
            pattern = r'(?:^|[\s\.,!?;:()\[\]\-_])' + re.escape(kw) + r'(?:$|[\s\.,!?;:()\[\]\-_])'
            if re.search(pattern, text):
                return True
        else:
            if kw in text:
                return True
    return False


def detect_category(text: str, file_hint: Optional[str] = None) -> str:
    """
    Определяет категорию чата по названию/описанию.
    file_hint — имя файла из ZIP для дополнительного контекста.
    Возвращает название категории или 'Другое'.
    """
    text_l = (text or "").lower()

    # Сначала проверяем по имени файла
    if file_hint:
        fh = os.path.splitext(os.path.basename(file_hint))[0].lower()
        for cat in ALL_CATS:
            if cat.lower() in fh:
                return cat
        for cat, kws in ALL_CATS.items():
            for kw in kws:
                if kw in fh:
                    return cat

    # Приоритетные категории
    for cat in PRIORITY_CATS:
        if cat in ALL_CATS and _check_keywords(text_l, ALL_CATS[cat]):
            return cat

    # Остальные категории
    for cat, kws in ALL_CATS.items():
        if _check_keywords(text_l, kws):
            return cat

    return "Другое"


def detect_city(text: str) -> str:
    """Определяет город по названию/описанию чата."""
    text_l = (text or "").lower()
    for city, kws in CITY_MAPPING.items():
        if _check_keywords(text_l, kws):
            return city
    return ""
